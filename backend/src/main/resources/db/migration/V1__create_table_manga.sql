CREATE TABLE manga (
    id                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url_image           VARCHAR2(500),
    title               VARCHAR2(255) NOT NULL,
    author              VARCHAR2(255),
    url_site            VARCHAR2(500),
    total_of_chapters   NUMBER(10),
    last_chapter_read   NUMBER(10) DEFAULT 0,
    format              VARCHAR2(20),
    status              VARCHAR2(20),

    CONSTRAINT chk_manga_format
        CHECK (format IN ('MANHWA', 'MANGA', 'MANHUA')),
    CONSTRAINT chk_manga_status
        CHECK (status IN ('LENDO', 'QUERO_LER', 'PAUSADOS', 'COMPLETO', 'ABANDONADO')),
    CONSTRAINT uk_manga_title_author
        UNIQUE (title, author)
);